package BraceExpressionII;

package leetCode;

import java.util.ArrayList;
import java.util.Collections;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

/* 1096. Brace Expansion II
Under the grammar given below, strings can represent a set of lowercase words. Let R(expr) denote the set of words the expression represents.

The grammar can best be understood through simple examples:

Single letters represent a singleton set containing that word.
R("a") = {"a"}
R("w") = {"w"}
When we take a comma-delimited list of two or more expressions, we take the union of possibilities.
R("{a,b,c}") = {"a","b","c"}
R("{{a,b},{b,c}}") = {"a","b","c"} (notice the final set only contains each word at most once)
When we concatenate two expressions, we take the set of possible concatenations between two words where the first word comes from the first expression and the second word comes from the second expression.
R("{a,b}{c,d}") = {"ac","ad","bc","bd"}
R("a{b,c}{d,e}f{g,h}") = {"abdfg", "abdfh", "abefg", "abefh", "acdfg", "acdfh", "acefg", "acefh"}
Formally, the three rules for our grammar:

For every lowercase letter x, we have R(x) = {x}.
For expressions e1, e2, ... , ek with k >= 2, we have R({e1, e2, ...}) = R(e1) ∪ R(e2) ∪ ...
For expressions e1 and e2, we have R(e1 + e2) = {a + b for (a, b) in R(e1) × R(e2)}, where + denotes concatenation, and × denotes the cartesian product.
Given an expression representing a set of words under the given grammar, return the sorted list of words that the expression represents.

 

Example 1:

Input: expression = "{a,b}{c,{d,e}}"
Output: ["ac","ad","ae","bc","bd","be"]
Example 2:

Input: expression = "{{a,z},a{b,c},{ab,z}}"
Output: ["a","ab","ac","z"]
Explanation: Each distinct word is written only once in the final answer.
 

Constraints:

1 <= expression.length <= 60
expression[i] consists of '{', '}', ','or lowercase English letters.
The given expression represents a set of words based on the grammar given in the description.
 * 
 * Time Complexity: O(P log P), (where $P$ is the total number of unique expanded words)
The parsing and evaluation time is proportional to the number of combinations generated by the grammar rules (Cartesian products and unions). Due to the 
		constraints ($expression.length ≤ 60$), the recursive descent parser executes efficiently, with the final sorting step operating on the resulting 
		set of size $P$ in ${O}(P \log P)$ time.
 * Space Complexity: O(P *L), Where $P$ is the number of unique words generated and $L$ is the maximum length of a word. The space is dominated by the hash 
 * 		sets storing intermediate and final generated combinations, along with the recursion stack depth which is bounded by the length/nesting of the 
 * 		expression ($≤ 60$).
 */

public class BraceExpansionII {
	
	private int pos = 0;
	private String s;

	public List<String> braceExpansionII(String expression) {
		this.s = expression;
		this.pos = 0;
		
		Set<String> resultSet = parseExpr();
		
		List<String> resultList = new ArrayList<>(resultSet);
		Collections.sort(resultList);
		return resultList;
	}
	
	// Parses comma-sperated terms (Union)
	private Set<String> parseExpr() {
		Set<String> res = new HashSet<>();
		res.addAll(parseTerm());
		
		while (pos < s.length() && s.charAt(pos) == ',') {
			pos++; // Consume the ','
			res.addAll(parseTerm());
		}
		
		return res;
	}
	
	// Parses adjacent factors (Concatenation / Cartesian Product)
	private Set<String> parseTerm() {
		Set<String> res = new HashSet<>();
		res.add(""); // Start with empty string to allow initial concatenation
		
		while (pos < s.length() && (s.charAt(pos) == '{' || Character.isLowerCase(s.charAt(pos)))) {
			Set<String> nextSet = parseFactor();
			Set<String> mergedSet = new HashSet<>();
			
			// Cartesian product of current results and the next evaluated factor
			for (String a : res) {
				for (String b : nextSet) {
					mergedSet.add(a + b);
				}
			}
			res = mergedSet;
		}
		
		return res;
	}
	
	// Parses a single block: either { expression } or a sequence of letters
	private Set<String> parseFactor() {
		if (s.charAt(pos) == '{') {
			pos++; // Consume '{'
			Set<String> res = parseExpr();
			pos++;  // Consume '}'
			return res;
		} else {
			// It's lowercase letter sequence
			StringBuilder sb = new StringBuilder();
			while (pos < s.length() && Character.isLowerCase(s.charAt(pos))) {
				sb.append(s.charAt(pos));
				pos++;
			}
			Set<String> res = new HashSet<>();
			res.add(sb.toString());
			return res;
		}
	}
	
	public static void main(String[] args) {
		BraceExpansionII sol = new BraceExpansionII();

		// Example 1
		String expr1 = "{a,b}{c,{d,e}}";
		System.out.println("Input: expression = \"" + expr1 + "\"");
		System.out.println("Output: " + sol.braceExpansionII(expr1)); 
		// Expected: ["ac", "ad", "ae", "bc", "bd", "be"]
		System.out.println("-----------------------------------");

		// Example 2
		String expr2 = "{{a,z},a{b,c},{ab,z}}";
		System.out.println("Input: expression = \"" + expr2 + "\"");
		System.out.println("Output: " + sol.braceExpansionII(expr2)); 
		// Expected: ["a", "ab", "ac", "z"]
	}
}
